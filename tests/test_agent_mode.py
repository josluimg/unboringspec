# --- prompt / render -------------------------------------------------------------


def test_prompt_writes_contract(in_tmp):
    r = runner.invoke(app, ["prompt", str(EXAMPLE)])
    assert r.exit_code == 0, r.output
    text = (in_tmp / ".unboring/001-photo-albums/prompt.md").read_text()
    assert '"one_liner"' in text  # JSON schema included
    assert "===== FILE: spec.md =====" in text
    assert "   1| # Feature Specification: Shared Photo Albums" in text
    assert "insights.json" in r.output


def test_render_validates_citations(in_tmp):
    wd = in_tmp / ".unboring/001-photo-albums"
    wd.mkdir(parents=True)
    # Agents often wrap JSON in fences; that must still work.
    (wd / "insights.json").write_text("```json\n" + json.dumps(_insights()) + "\n```")
    r = runner.invoke(app, ["render", str(EXAMPLE)])
    assert r.exit_code == 0, r.output
    assert "Dropped 1 item" in r.output
    html = (wd / "review.html").read_text()
    assert "One permanent token per album" in html
    assert "Cites a line that does not exist" not in html
    assert "generated by agent" in html


def test_render_without_insights_explains(in_tmp):
    r = runner.invoke(app, ["render", str(EXAMPLE)])
    assert r.exit_code == 1
    assert "unboring prompt" in r.output


def test_render_rejects_bad_json(in_tmp):
    wd = in_tmp / ".unboring/001-photo-albums"
    wd.mkdir(parents=True)
    (wd / "insights.json").write_text('{"one_liner": "missing fields"}')
    r = runner.invoke(app, ["render", str(EXAMPLE)])
    assert r.exit_code == 1
    assert "not valid insights JSON" in r.output


# --- init ------------------------------------------------------------------------


def test_init_installs_skills(in_tmp):
    r = runner.invoke(app, ["init", "--ai", "claude", "--ai", "copilot", "--ai", "gemini"])
    assert r.exit_code == 0, r.output
    skill = (in_tmp / ".claude/skills/unboring-review/SKILL.md").read_text()
    assert skill.startswith("---\nname: unboring-review\n")
    assert "unboring prompt" in skill and "unboring render" in skill
    # Claude Code pre-approves only the unboring CLI; nothing broader.
    frontmatter = skill.split("---\n")[1]
    assert "allowed-tools: Bash(unboring:*)\n" in frontmatter
    assert frontmatter.count("allowed-tools") == 1
    # Other agents get the same instructions without Claude-specific fields.
    copilot = (in_tmp / ".github/skills/unboring-review/SKILL.md").read_text()
    assert "allowed-tools" not in copilot
    assert copilot.split("---\n", 2)[2] == skill.split("---\n", 2)[2]
    toml = tomllib.loads((in_tmp / ".gemini/commands/unboring.review.toml").read_text())
    assert "{{args}}" in toml["prompt"]
    assert ".unboring/" in (in_tmp / ".gitignore").read_text()


def test_init_is_idempotent_and_respects_existing(in_tmp):
    (in_tmp / ".gitignore").write_text("node_modules/")
    runner.invoke(app, ["init", "--ai", "codex"])
    target = in_tmp / ".agents/skills/unboring-review/SKILL.md"
    target.write_text("custom")
    r = runner.invoke(app, ["init", "--ai", "codex"])
    assert "exists" in r.output
    assert target.read_text() == "custom"
    assert (in_tmp / ".gitignore").read_text().count(".unboring/") == 1
    assert (in_tmp / ".gitignore").read_text().startswith("node_modules/\n")


