def test_speckit_v144_fixture():
    folder = FIXTURES / "v1.4.4/002-login"
    ir = get_adapter(folder).load(folder)
    assert ir.warnings == []
    qs = [q.question for q in ir.questions]
    assert "expiry time not specified" in qs
    assert "Primary Dependencies is not decided yet" in qs  # bare marker in plan.md
    assert [q.id for q in ir.questions] == [f"Q{i}" for i in range(1, len(qs) + 1)]
    titles = [d.title for d in ir.decisions]
    assert "Language/Version" in titles
    assert "Primary Dependencies" not in titles and "Storage" not in titles
    assert ir.tasks[1].parallel and ir.tasks[1].story == "US1"


